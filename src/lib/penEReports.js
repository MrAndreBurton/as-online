function isPlainObject(value) {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value)
  );
}

function isStringArray(value) {
  return (
    Array.isArray(value) &&
    value.every((item) => typeof item === "string")
  );
}

export function validatePenEStudentReportDraft(value) {
  const errors = [];

  if (!isPlainObject(value)) {
    return {
      valid: false,
      errors: ["The Pen-E response must be a JSON object."],
    };
  }

  const allowedTopLevelKeys = [
    "report_version",
    "overview",
    "learning_highlights",
    "areas_for_development",
    "follow_up_priorities",
    "curriculum_progress",
    "closing_comment",
  ];

  const extraKeys = Object.keys(value).filter(
    (key) => !allowedTopLevelKeys.includes(key)
  );

  if (extraKeys.length > 0) {
    errors.push(
      `Unexpected fields: ${extraKeys.join(", ")}`
    );
  }

  if (value.report_version !== "student-content-v1") {
    errors.push(
      'report_version must be "student-content-v1".'
    );
  }

  if (!isPlainObject(value.overview)) {
    errors.push("overview must be an object.");
  } else {
    if (typeof value.overview.headline !== "string") {
      errors.push("overview.headline must be a string.");
    }

    if (typeof value.overview.summary !== "string") {
      errors.push("overview.summary must be a string.");
    }
  }

  if (!isStringArray(value.learning_highlights)) {
    errors.push("learning_highlights must be an array of strings.");
  }

  if (!isStringArray(value.areas_for_development)) {
    errors.push(
      "areas_for_development must be an array of strings."
    );
  }

  if (!isStringArray(value.follow_up_priorities)) {
    errors.push(
      "follow_up_priorities must be an array of strings."
    );
  }

  if (!isStringArray(value.curriculum_progress)) {
    errors.push(
      "curriculum_progress must be an array of strings."
    );
  }

  if (typeof value.closing_comment !== "string") {
    errors.push("closing_comment must be a string.");
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}

export function parsePenEStudentReportDraft(rawText) {
  if (typeof rawText !== "string") {
    return {
      valid: false,
      data: null,
      errors: [
        "The pasted Pen-E response must be text.",
      ],
    };
  }

  let cleaned = rawText.trim();

  // ----------------------------------------------------------
  // 1. Strip accidental Markdown code fences
  //
  // Handles:
  // ```json
  // { ... }
  // ```
  //
  // and:
  // ```
  // { ... }
  // ```
  // ----------------------------------------------------------

  cleaned = cleaned
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim();


  // ----------------------------------------------------------
  // 2. Normalize curly / smart quotation marks
  //
  // “ ” -> "
  // ‘ ’ -> '
  //
  // JSON specifically requires straight double quotes.
  // ----------------------------------------------------------

  cleaned = cleaned
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2018\u2019]/g, "'");


  // ----------------------------------------------------------
  // 3. Extract the JSON object if surrounding prose was pasted
  //
  // Example:
  // Here is the JSON:
  // { ... }
  // Hope this helps.
  //
  // We only extract between the first { and final }.
  // ----------------------------------------------------------

  const firstBrace =
    cleaned.indexOf("{");

  const lastBrace =
    cleaned.lastIndexOf("}");

  if (
    firstBrace !== -1 &&
    lastBrace !== -1 &&
    lastBrace > firstBrace
  ) {
    cleaned = cleaned
      .slice(
        firstBrace,
        lastBrace + 1
      )
      .trim();
  }


  // ----------------------------------------------------------
  // 4. Parse JSON
  // ----------------------------------------------------------

  let parsed;

  try {
    parsed =
      JSON.parse(cleaned);
  } catch (error) {
    return {
      valid: false,
      data: null,
      errors: [
        "The pasted Pen-E response is not valid JSON.",
        error?.message
          ? `JSON error: ${error.message}`
          : null,
      ].filter(Boolean),
    };
  }


  // ----------------------------------------------------------
  // 5. Strict AEOS schema validation
  // ----------------------------------------------------------

  const validation =
    validatePenEStudentReportDraft(
      parsed
    );

  return {
    valid:
      validation.valid,

    data:
      validation.valid
        ? parsed
        : null,

    errors:
      validation.errors,

    cleanedText:
      cleaned,
  };
}

