const STUDENT_REPORT_PROMPT_VERSION = "student-report-draft-v1";

function safeArray(value) {
  return Array.isArray(value) ? value : [];
}

function cleanEvidenceItem(item = {}) {
  return {
    evidence_type: item.evidence_type ?? null,
    statement: item.statement ?? "",
    explanation: item.explanation ?? null,
    confidence: item.confidence ?? null,
    session_id: item.session_id ?? null,
    curriculum_node_id: item.curriculum_node_id ?? null,
  };
}

function cleanActionItem(item = {}) {
  return {
    action_origin: item.action_origin ?? null,
    action_type: item.action_type ?? null,
    title: item.title ?? "",
    description: item.description ?? null,
    target_role: item.target_role ?? null,
    confidence: item.confidence ?? null,
    session_id: item.session_id ?? null,
  };
}

function cleanSessionItem(item = {}) {
  return {
    session_id: item.session_id ?? null,
    date: item.date ?? null,
    session_title: item.session_title ?? null,
    offering_name: item.offering_name ?? null,
    tutor_name: item.tutor_name ?? null,
    duration_minutes: item.duration_minutes ?? null,
    attendance_status: item.attendance_status ?? null,
    session_summary: item.session_summary ?? null,
  };
}

export function buildPenEStudentReportPackage(report) {
  if (!report) {
    throw new Error("Report is required.");
  }

  if (report.subject_type !== "student") {
    throw new Error(
      "Pen-E Student Report Drafting only supports student reports."
    );
  }

  const snapshot = report.data_snapshot ?? {};

  const student = snapshot.student ?? {};
  const reportingPeriod = snapshot.reporting_period ?? {
    type: report.report_type ?? null,
    start: report.period_start ?? null,
    end: report.period_end ?? null,
  };

  return {
    package_type: "aeos_pen_e_student_report_draft",
    package_version: "1.0",
    prompt_version: STUDENT_REPORT_PROMPT_VERSION,

    report_context: {
      report_id: report.report_id,
      report_type: report.report_type,
      report_title: report.report_title,
      report_status: report.report_status,
      period_start: report.period_start,
      period_end: report.period_end,
    },

    student: {
      student_id: student.student_id ?? report.student_id ?? null,
      first_name: student.first_name ?? null,
      last_name: student.last_name ?? null,
      display_name: student.display_name ?? null,
      school: student.school ?? null,
    },

    reporting_period: reportingPeriod,

    session_metrics: snapshot.session_metrics ?? {},

    attendance: snapshot.attendance ?? {},

    offerings: safeArray(snapshot.offerings),

    tutors: safeArray(snapshot.tutors),

    sessions: safeArray(snapshot.sessions).map(cleanSessionItem),

    reviewed_learning_evidence: safeArray(
      snapshot.learning_evidence
    ).map(cleanEvidenceItem),

    reviewed_actions: safeArray(snapshot.actions).map(cleanActionItem),

    reviewed_curriculum_matches: safeArray(
      snapshot.curriculum?.reviewed_matches
    ),

    instructions: getStudentReportDraftInstructions(),
  };
}

